# Collects markdown sections while the scripts run;
# run_all.R writes them to docs/results.md.

.report <- new.env()
.report$sections <- character(0)

report_add <- function(...) {
  .report$sections <- c(.report$sections, paste0(..., collapse = ""))
}

md_table <- function(df) {
  fmt <- function(x) {
    if (is.numeric(x))
      format(x, big.mark = ",", trim = TRUE) else as.character(x)
  }
  
  cells <- vapply(df, fmt, character(nrow(df)))
  if (is.null(dim(cells))) cells <- matrix(cells, nrow = 1)
  c(paste0("| ", paste(names(df), collapse = " | "), " |"),
    paste0("|", paste(rep("---", ncol(df)), collapse = "|"), "|"),
    apply(cells, 1, function(r) paste0("| ", paste(r, collapse = " | "), " |")))
}

report_write <- function(path) {
  header <- c("# Results",
              "",
              "Generated by `Rscript run_all.R`. Inputs are **illustrative assumptions for a",
              "hypothetical mid-size company** (`data/assumptions/*.csv`), not benchmarks.",
              "")
  writeLines(c(header, .report$sections), path)
}

save_plot <- function(plot, name, width = 8, height = 5) {
  ggplot2::ggsave(file.path("docs", "figures", name), plot,
                  width = width, height = height, dpi = 120, bg = "white")
}
