# One-page board brief (docs/board-brief.md), built from the tables the earlier
# scripts wrote to outputs/. Nothing here is simulated.

summary_tbl <- read.csv("outputs/annual_loss_summary.csv")
se_tbl      <- read.csv("outputs/annual_loss_mc_error.csv")
roi         <- read.csv("outputs/control_roi.csv")
uncert      <- read.csv("outputs/control_rosi_uncertainty.csv")
tol         <- read.csv("outputs/tolerance_check.csv")
overlap     <- readRDS("outputs/tolerance_overlap.rds")
combined    <- readRDS("outputs/combined_avoided_by_year.rds")
sens        <- read.csv("outputs/sensitivity.csv")
sev         <- read.csv("outputs/control_rosi_severity.csv")

total <- summary_tbl[summary_tbl$scenario == "Total", ]
total_se <- se_tbl[se_tbl$scenario == "Total", ]
risks <- summary_tbl[summary_tbl$scenario != "Total", ]
risks <- risks[order(-risks$p95), ]
ctl <- merge(roi, uncert, by = "control", sort = FALSE)
ctl <- ctl[order(-ctl$rosi), ]
breaches <- tol[tol$p_before > tol$max_probability, ]
# the event rate drives the chance of losing money only if, with the rate known,
# no control loses money
rate_drives_it <- all(ctl$p_rosi_negative_rate_known < 0.001)

pct <- function(x, digits = 0) sprintf(paste0("%.", digits, "f%%"), 100 * x)
# chance-of-loss figures: one decimal below 10%, so 1.4% doesn't read as 1%
pct_risk <- function(x) ifelse(x < 0.1, pct(x, 1), pct(x, 0))
pct_span <- function(x) {
  lo <- pct_risk(min(x))
  hi <- pct_risk(max(x))
  if (lo == hi) paste("about", lo) else paste0(lo, "–", hi)
}
signed <- function(x) sprintf("%+.0f%%", 100 * x)
md <- function(df) paste(md_table(df), collapse = "\n")

tolerance_line <- if (nrow(breaches) == 0) {
  "Today's loss exceedance curve is **within** the stated risk tolerance."
} else {
  paste0("Today's exposure is **outside** the stated risk tolerance for annual losses between about ",
         dollars_sig(overlap$over_before[1], 2), " and ", dollars_sig(overlap$over_before[2], 2),
         ". For example, the chance of losing more than ", dollars_sig(breaches$loss[1], 2),
         " in a year is ", pct(breaches$p_before[1], 1), " against a tolerance of ",
         pct(breaches$max_probability[1], 1), ".")
}
after_line <- if (is.na(overlap$over_after[1])) {
  "With the controls below, the curve comes back **within** tolerance."
} else {
  paste0("Even with the proposed controls, the curve stays outside tolerance between about ",
         dollars_sig(overlap$over_after[1], 2), " and ", dollars_sig(overlap$over_after[2], 2), ".")
}

risk_tbl <- data.frame(
  Scenario = risks$scenario[1:3],
  `1-in-20-year loss` = dollars_sig(risks$p95[1:3]),
  `Expected per year` = dollars_sig(risks$mean[1:3]),
  `Chance of any loss in a year` = pct(risks$p_any_loss[1:3]),
  check.names = FALSE
)
ctl_tbl <- data.frame(
  Control = ctl$control,
  `Cost / yr` = dollars_sig(ctl$annual_cost, 2),
  `Expected return` = signed(ctl$rosi),
  `Plausible range (90%)` = paste(signed(ctl$rosi_p05), "to", signed(ctl$rosi_p95)),
  `Chance it loses money` = pct_risk(ctl$p_rosi_negative),
  check.names = FALSE
)

brief <- c(
  "# Cyber risk: board brief",
  "",
  "*Generated by `Rscript run_all.R` from [`results.md`](results.md). Illustrative inputs",
  "for a hypothetical mid-size company; see the assumptions at the end.*",
  "",
  "## Bottom line",
  "",
  paste0("- **Expected cyber loss: ", dollars_sig(total$mean), " a year.** In a bad year ",
         "(1 in 20) it reaches ", dollars_sig(total$p95), "; in a very bad year (1 in 100), ",
         dollars_sig(total$p99), "."),
  paste0("- ", tolerance_line),
  paste0("- ", after_line),
  paste0("- **Strongest case: ", ctl$control[1], "** (", signed(ctl$rosi[1]), " expected return, ",
         pct_risk(ctl$p_rosi_negative[1]), " chance it loses money)."),
  if (all(ctl$rosi[-1] > 0))
    paste0("- The other controls also pay off on average, but the chance that each costs ",
           "more than it saves is ", pct_span(ctl$p_rosi_negative[-1]),
           if (rate_drives_it) ", because we don't know how often those incidents happen" else "",
           "."),
  paste0("- Together they cost ", dollars_sig(sum(roi$annual_cost)), " a year and cut ",
         "expected loss by ", dollars_sig(mean(combined)), " a year."),
  if (all(ctl$rosi > 0) && max(ctl$evpi / ctl$annual_cost) < 0.1)
    paste0("- **Waiting for better estimates is not worth it:** perfect information about ",
           "any control would be worth at most ", dollars_sig(max(ctl$evpi), 2),
           " a year, a small fraction of its cost."),
  "",
  "![Loss exceedance vs. tolerance](figures/loss_exceedance_tolerance.png)",
  "",
  "## Top risks by bad-year loss",
  "",
  "Ranked by the 1-in-20-year loss, not the average: the average hides rare, severe events.",
  "",
  md(risk_tbl),
  "",
  "## Proposed controls",
  "",
  md(ctl_tbl),
  "",
  paste0("The range reflects what we don't know: how often each incident happens and how ",
         "well the control works.",
         if (rate_drives_it) " Almost all of the risk of losing money comes from the first." else ""),
  "",
  "## Assumptions and limits",
  "",
  "> - Frequencies and loss ranges are **illustrative expert estimates**, not benchmarks.",
  if (any(sens$p_ext > 0))
    paste0("> - Scenarios are simulated as independent. If ", pct(sens$p_ext[sens$p_ext > 0]),
           " of ransomware attacks also leaked customer data, the 1-in-100-year loss would ",
           "rise from ", dollars_sig(sens$p99[1]), " to ", dollars_sig(sens$p99[sens$p_ext > 0]), ".")
  else "> - Scenarios are simulated as independent.",
  paste0("> - The range for each control treats the size of a loss as known. With loss sizes ",
         "uncertain too (each 90% interval ", sev$loss_uncertainty[1], " times wider), the chance ",
         "each control loses money becomes ", pct_span(sev$p_rosi_negative), "."),
  paste0("> - Figures carry Monte Carlo error: the expected loss is ± ", dollars_sig(total_se$se_mean, 2),
         " and the 1-in-100-year loss ± ", dollars_sig(total_se$se_p99, 2), "."),
  "> - The risk tolerance curve is illustrative; the board would set its own.",
  ""
)
writeLines(brief, "docs/board-brief.md")
